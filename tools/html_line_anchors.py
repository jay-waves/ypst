#!/usr/bin/env python3
"""Compile Typst HTML with source-line anchors using Tree-sitter."""
import re
import json
from functools import lru_cache
from pathlib import Path
from urllib.parse import quote


@lru_cache(maxsize=1)
def typst_parser():
    from tree_sitter_language_pack import get_parser
    return get_parser("typst")


def check_document_settings(source):
    """Explain the template's top-level document metadata requirement."""
    try:
        data = source.encode("utf-8")
        tree = typst_parser().parse(data)
    except Exception as error:
        raise ValueError(f"could not load the Typst grammar: {error}") from error
    if tree.root_node.has_error:
        return
    template_seen = False
    for node in tree.root_node.named_children:
        if node.type != "code" or len(node.named_children) != 1:
            continue
        child = node.named_children[0]
        text = data[child.start_byte:child.end_byte]
        if child.type == "show" and re.match(rb"show\s*:\s*template\b", text):
            template_seen = True
        elif template_seen and child.type == "set" and re.match(rb"set\s+document\s*\(", text):
            line = data.count(b"\n", 0, node.start_byte) + 1
            raise ValueError(f"line {line}: #set document must appear before #show: template; move the document setting above the template show rule")


def inject(source):
    try:
        parser = typst_parser()
    except ImportError as error:
        raise ValueError("install dependencies: python -m pip install -r requirements.txt") from error
    data = source.encode("utf-8")
    try:
        tree = parser.parse(data)
    except Exception as error:
        raise ValueError(f"could not load the Typst grammar: {error}") from error
    if tree.root_node.has_error:
        raise ValueError("Typst syntax tree contains errors; refusing to inject markers")
    anchors = {}
    labels = set(re.findall(r"<L([1-9]\d*)>", source))

    def mark(node, heading=False):
        line = data.count(b"\n", 0, node.start_byte) + 1
        if str(line) in labels:
            raise ValueError(f"line anchor L{line} conflicts with a source label")
        if line in anchors:
            return
        offset = node.start_byte
        if heading:
            prefix = re.match(rb'=+[ \t]+', data[offset:node.end_byte])
            if not prefix:
                return
            offset += prefix.end()
        marker = (f'#html.elem("span", attrs: (id: "L{line}", '
                  f'"data-line": "{line}", class: "source-line-anchor"))')
        anchors[line] = (offset, marker.encode())

    def visit(container):
        paragraph_start = True
        for node in container.named_children:
            if node.type == "section":
                visit(node)
                paragraph_start = True
            elif node.type == "heading":
                mark(node, heading=True)
                paragraph_start = True
            elif node.type == "content":
                visit(node)
                paragraph_start = True
            elif node.type == "parbreak":
                paragraph_start = True
            elif node.type == "comment":
                continue
            else:
                if paragraph_start and node.type == "text" and data[node.start_byte:node.end_byte].strip():
                    mark(node)
                paragraph_start = False

    visit(tree.root_node)
    chunks = []
    previous = 0
    for offset, marker in sorted(anchors.values()):
        chunks.extend((data[previous:offset], marker))
        previous = offset
    chunks.append(data[previous:])
    return b"".join(chunks).decode("utf-8")


def rewrite_main_images(source, source_dir, root, origin):
    """Rewrite simple literal main-file image calls for the preview server."""
    try:
        parser = typst_parser()
    except ImportError as error:
        raise ValueError("install dependencies: python -m pip install -r requirements.txt") from error
    data = source.encode("utf-8")
    tree = parser.parse(data)
    if tree.root_node.has_error:
        raise ValueError("Typst syntax tree contains errors; refusing image rewrite")
    edits = []

    def visit(node):
        if node.type == "call":
            children = node.named_children
            if len(children) == 2 and children[0].type == "ident" and children[1].type == "group":
                name, group = children
                args = group.named_children
                if data[name.start_byte:name.end_byte] == b"image" and args and args[0].type == "string":
                    # Keep complex sizing, generated bytes and custom options on
                    # Typst's native path until their semantics are supported.
                    extra = data[args[0].end_byte:group.end_byte - 1].decode("utf-8")
                    if not re.fullmatch(r"\s*(?:,\s*(?:width|height)\s*:\s*\d+(?:\.\d+)?%\s*)?[,]?\s*", extra):
                        return
                    try:
                        value = json.loads(data[args[0].start_byte:args[0].end_byte])
                        if not isinstance(value, str) or not value or value.startswith("/"):
                            return
                        image = (source_dir / value).resolve()
                        relative = image.relative_to(root)
                        if image.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp", ".svg"} or not image.is_file():
                            return
                    except (ValueError, OSError):
                        return
                    url = origin + "/__source/" + quote(relative.as_posix(), safe="/")
                    replacement = '__ypst_preview_image.with(' + json.dumps(url, ensure_ascii=False) + ')'
                    edits.append((name.start_byte, name.end_byte, replacement.encode("utf-8")))
                    return
        for child in node.named_children:
            visit(child)

    visit(tree.root_node)
    if not edits:
        return source
    for start, end, replacement in sorted(edits, reverse=True):
        data = data[:start] + replacement + data[end:]
    return data.decode("utf-8")


